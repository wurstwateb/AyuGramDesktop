"""Deterministic test vectors shared by the Python, C++ and Android implementations.

Regenerate docs/sync/test-vectors.json with:
    python -m tests.vectors
"""
from __future__ import annotations

import json
from pathlib import Path

from typsync import crypto
from typsync import events as ev

VECTORS_PATH = Path(__file__).resolve().parents[2] / "docs" / "sync" / "test-vectors.json"


def _bytes(start: int, n: int = 32) -> bytes:
    return bytes((start + i) % 256 for i in range(n))


def _events() -> list[ev.Event]:
    return [
        ev.Event(ev.MESSAGE, 123456789, snapshot=ev.Snapshot(
            dialog=-1234567890, msg_id=42, from_id=987654321, date=1761900000,
            text="Привет, мир! 👋",
            entities=[{"type": "bold", "offset": 0, "length": 6}],
            media=ev.Media("0f" * 16, "image/jpeg", 48213, "photo"))),
        ev.Event(ev.EDIT, 123456789, previous=ev.Snapshot(
            dialog=555, msg_id=7, from_id=555, date=1761900100, edit_date=0,
            text="старая версия", reply_to=5), new_edit_date=1761900200),
        ev.Event(ev.DELETE, 123456789, dialog=0, msg_ids=[9, 8], date=1761900300,
                 snapshots=[ev.Snapshot(dialog=555, msg_id=8, from_id=555,
                                        date=1761900250, text="удалённое")]),
        ev.Event(ev.DELETE, 123456789, dialog=-1234567890, msg_ids=[100], date=1761900400),
        ev.Event(ev.MESSAGE, 123456789, snapshot=ev.Snapshot(
            dialog=555, msg_id=11, from_id=555, date=1761900500, text="")),
    ]


def build() -> dict:
    owner_priv = _bytes(1)
    owner_pub = crypto.public_from_private(owner_priv)
    seals = []
    for i, event in enumerate(_events()):
        plaintext = event.encode()
        eph = _bytes(100 + i)
        nonce = _bytes(200 + i, crypto.NONCE_SIZE)
        seals.append({
            "event": event.to_json(),
            "plaintextHex": plaintext.hex(),
            "ephemeralPrivateHex": eph.hex(),
            "nonceHex": nonce.hex(),
            "blobHex": crypto.seal(owner_pub, plaintext,
                                   ephemeral_private=eph, nonce=nonce).hex(),
            "dedupKeys": ev.dedup_keys(event),
            "relayKey": ev.relay_key(event),
        })
    code = "7K3M-QX9P-2ZDW"
    pair_nonce = _bytes(250, crypto.NONCE_SIZE)
    return {
        "comment": "Generated by sync-server/tests/vectors.py; do not edit by hand.",
        "ownerPrivateHex": owner_priv.hex(),
        "ownerPublicHex": owner_pub.hex(),
        "seal": seals,
        "pair": {
            "code": code,
            "codeAsTyped": "7k3m qx9p 2zdw",
            "normalized": crypto.normalize_pair_code(code),
            "lookupHash": crypto.pair_lookup_hash(code),
            "payloadHex": owner_priv.hex(),
            "nonceHex": pair_nonce.hex(),
            "encryptedHex": crypto.pair_encrypt(code, owner_priv, nonce=pair_nonce).hex(),
        },
    }


def write() -> None:
    VECTORS_PATH.write_text(
        json.dumps(build(), ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    write()
    print(VECTORS_PATH)
